def cite_ref(idx, style="ieee", topic="layanan-publik"):
    dataset = REFS_APK_KUHP if topic == "apk-kuhp" else REFS_HUMAS
    if style == "apa":
        for item in dataset:
            if item["id"] == idx:
                return item["apa_cite"]
    return f"[{idx}]"


def get_reference_list(style="ieee", topic="layanan-publik", count=25):
    dataset = REFS_APK_KUHP if topic == "apk-kuhp" else REFS_HUMAS
    subset = dataset[:max(count, 10)]
    if style == "apa":
        return sorted([item["apa"] for item in subset])
    return [item["ieee"] for item in subset]


